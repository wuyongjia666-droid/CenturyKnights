#!/usr/bin/env python3
"""Write project/data/art/genome_bank_index.json: the farm manifest rows that have a plate on disk.

Exports do not carry tools/farm_queue/genome_bank_v92.json (it sits outside project/), so
CKPortraitBank used to skip exact matching on device and pick a same-stage plate by seed. This
compact index keeps what match_identity needs (stage, sex, bloodline, identity tokens) for every
bucket that actually has a plate, with the tokens dictionary-encoded.

  python3 tools/art/write_bank_index.py          # rewrite
  python3 tools/art/write_bank_index.py --check  # CI: fail if the file is stale

Run after every bank ingest, after write_bank_stems.py.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "tools/farm_queue/genome_bank_v92.json"
STEMS = ROOT / "project/data/art/genome_bank_stems.json"
OUT = ROOT / "project/data/art/genome_bank_index.json"


def build() -> dict:
    man = json.loads(MANIFEST.read_text(encoding="utf-8"))
    stems = json.loads(STEMS.read_text(encoding="utf-8")).get("stems", {})
    plated = {s for arr in stems.values() for s in arr}
    rows = sorted((b for b in man["buckets"] if b["bucket_key"] in plated), key=lambda b: b["bucket_key"])
    vocab = sorted({str(t) for b in rows for t in b["identity"]})
    tok = {t: i for i, t in enumerate(vocab)}
    bloods = sorted({str(b.get("bloodline", "")) for b in rows})
    bl = {b: i for i, b in enumerate(bloods)}
    out_rows = []
    for b in rows:
        sex = str(b.get("sex", ""))
        if sex not in ("m", "f"):
            raise SystemExit("bucket %s has no sex" % b["bucket_key"])
        out_rows.append([b["bucket_key"], sex, bl[str(b.get("bloodline", ""))], sorted(tok[str(t)] for t in b["identity"])])
    return {
        "version": 1,
        "note": "generated by tools/art/write_bank_index.py from genome_bank_v92.json; rows = [bucket_key, sex, bloodline idx, identity token idx]",
        "manifest_buckets": len(man["buckets"]),
        "vocab": vocab,
        "bloodlines": bloods,
        "rows": out_rows,
    }


def render(data: dict) -> str:
    return json.dumps(data, ensure_ascii=False, separators=(",", ":")) + "\n"


def main() -> int:
    text = render(build())
    if "--check" in sys.argv:
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if cur != text:
            print("BANK INDEX SYNC FAIL: run python3 tools/art/write_bank_index.py")
            return 1
        print("BANK INDEX SYNC PASS rows=%d bytes=%d" % (len(json.loads(text)["rows"]), len(text.encode())))
        return 0
    OUT.write_text(text, encoding="utf-8")
    d = json.loads(text)
    print("wrote", OUT, "rows", len(d["rows"]), "vocab", len(d["vocab"]), "bytes", len(text.encode()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
